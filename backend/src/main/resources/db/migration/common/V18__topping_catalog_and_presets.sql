-- Server-owned preset catalogue. The frontend currently hardcodes its presets;
-- this table is the backend source of truth a future build can fetch from, so
-- the menu lives in one place instead of being duplicated in the client.
-- toppings reuses the same JSON {id,quantity} shape as orders.toppings.
CREATE TABLE pizza_preset (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50)   NOT NULL UNIQUE,
    name        VARCHAR(100)  NOT NULL,
    description VARCHAR(255),
    pizza_size  VARCHAR(5)    NOT NULL,
    sauce_type  VARCHAR(20)   NOT NULL DEFAULT 'ROBUST_TOMATO',
    crust_style VARCHAR(20)   NOT NULL DEFAULT 'HAND_TOSSED',
    toppings    VARCHAR(2000) NOT NULL DEFAULT '[]',
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order  INT           NOT NULL DEFAULT 0
);

