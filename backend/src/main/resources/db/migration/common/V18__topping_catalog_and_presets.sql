-- Promote the kitchen's topping allow-list out of a hardcoded Java Set
-- (the old ToppingCatalog.IDS) into a real table, so toppings can be enabled or
-- retired without a redeploy and the order validator reads its allow-list from
-- the database. Codes match the frontend topping art ids exactly.
CREATE TABLE topping (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(50)  NOT NULL UNIQUE,
    name     VARCHAR(100) NOT NULL,
    category VARCHAR(30)  NOT NULL,
    active   BOOLEAN      NOT NULL DEFAULT TRUE
);

