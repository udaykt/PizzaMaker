CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oid              VARCHAR(36)  NOT NULL UNIQUE,
    user_id          BIGINT       NOT NULL REFERENCES users(id),
    sauce            BOOLEAN      NOT NULL DEFAULT FALSE,
    mozzarella       BOOLEAN      NOT NULL DEFAULT FALSE,
    cheese           BOOLEAN      NOT NULL DEFAULT FALSE,
    pepperoni        BOOLEAN      NOT NULL DEFAULT FALSE,
    pepperoni_medium BOOLEAN      NOT NULL DEFAULT FALSE,
    sausage          BOOLEAN      NOT NULL DEFAULT FALSE,
    sausage_medium   BOOLEAN      NOT NULL DEFAULT FALSE,
    peppers          BOOLEAN      NOT NULL DEFAULT FALSE,
    peppers_medium   BOOLEAN      NOT NULL DEFAULT FALSE,
    olives           BOOLEAN      NOT NULL DEFAULT FALSE,
    olives_medium    BOOLEAN      NOT NULL DEFAULT FALSE,
    pizza_size       VARCHAR(5)   NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL
);
